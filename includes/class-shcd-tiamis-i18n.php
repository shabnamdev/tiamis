/**
 * Lightweight runtime translations for the plugin-owned admin application and widget.
 * WordPress gettext remains available for repository translations; this layer enables
 * an immediate language switch without reloading the administration page.
 */
class Tiamis_Chat_I18n {
	const LANG_FA = 'fa';
	const LANG_AR = 'ar';
	const LANG_EN = 'en';

	public static function allowed_languages() {
		return array( self::LANG_FA, self::LANG_AR, self::LANG_EN );
	}

	public static function normalize( $language, $fallback = self::LANG_FA ) {
		$language = sanitize_key( (string) $language );
		return in_array( $language, self::allowed_languages(), true ) ? $language : $fallback;
	}

	public static function admin_language() {
		$settings = get_option( defined( 'TIAMIS_CHAT_OPTION' ) ? TIAMIS_CHAT_OPTION : 'shcd_tiamis_settings', array() );
		return self::normalize( is_array( $settings ) && isset( $settings['admin_language'] ) ? $settings['admin_language'] : self::LANG_FA );
	}

	public static function widget_language() {
		$settings = get_option( defined( 'TIAMIS_CHAT_OPTION' ) ? TIAMIS_CHAT_OPTION : 'shcd_tiamis_settings', array() );
		return self::normalize( is_array( $settings ) && isset( $settings['widget_language'] ) ? $settings['widget_language'] : self::LANG_FA );
	}

	public static function direction( $language ) {
		return self::LANG_EN === self::normalize( $language ) ? 'ltr' : 'rtl';
	}

	public static function locale( $language ) {
		$map = array( self::LANG_FA => 'fa-IR', self::LANG_AR => 'ar', self::LANG_EN => 'en-US' );
		$language = self::normalize( $language );
		return $map[ $language ];
	}

	public static function language_names() {
		return array( self::LANG_FA => 'فارسی', self::LANG_AR => 'العربية', self::LANG_EN => 'English' );
	}

	public static function brand_name( $language = null ) {
		$language = self::normalize( null === $language ? self::admin_language() : $language );
		return self::LANG_EN === $language ? 'Tiamis' : 'تیامیس';
	}

